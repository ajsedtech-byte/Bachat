/**
 * Copy public/ → www/ and inject native API base URL for Capacitor WebView.
 * Relative /api/* fetch fails in the app shell; dashboards use localStorage bachat_api_base.
 *
 * Set in .env:
 *   MOBILE_API_BASE_URL=https://your-production-host.com
 * or reuse:
 *   PUBLIC_APP_URL=https://your-production-host.com
 *
 *   npm run mobile:prepare
 */
const fs = require("fs");
const path = require("path");
require("dotenv").config({ path: path.join(__dirname, "..", ".env") });

const root = path.join(__dirname, "..");
const publicDir = path.join(root, "public");
const wwwDir = path.join(root, "www");

function rmDir(dir) {
  if (!fs.existsSync(dir)) return;
  fs.rmSync(dir, { recursive: true, force: true });
}

function copyRecursive(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    const s = path.join(src, name);
    const d = path.join(dest, name);
    if (fs.statSync(s).isDirectory()) copyRecursive(s, d);
    else fs.copyFileSync(s, d);
  }
}

const fromEnv =
  (process.env.MOBILE_API_BASE_URL || process.env.PUBLIC_APP_URL || "").trim().replace(/\/+$/, "");

if (!fromEnv) {
  console.warn(
    "[mobile:prepare] MOBILE_API_BASE_URL (or PUBLIC_APP_URL) is not set. " +
      "The app shell will still build, but API calls need a full HTTPS base until you set it and re-run prepare."
  );
}

const nativeInitDir = path.join(wwwDir, "js");
const nativeInitPath = path.join(nativeInitDir, "native-init.js");
const initSource = `/* Generated by npm run mobile:prepare — do not edit */
window.__BACHAT_API_BASE__ = ${JSON.stringify(fromEnv)};
(function () {
  try {
    var C = window.Capacitor;
    if (!C || typeof C.isNativePlatform !== "function" || !C.isNativePlatform()) return;
    var b = window.__BACHAT_API_BASE__;
    if (b && String(b).trim()) {
      localStorage.setItem("bachat_api_base", String(b).replace(/\\/+$/, ""));
    }
  } catch (e) {}
})();
`;

const injectMarker = "native-init.js";

function injectNativeInit(htmlPath) {
  let html = fs.readFileSync(htmlPath, "utf8");
  if (html.includes(injectMarker)) return;
  const tag = `  <script src="/js/native-init.js"></script>\n`;
  if (html.includes("<head")) {
    html = html.replace(/<head([^>]*)>/i, (m) => `${m}\n${tag}`);
  } else {
    html = tag + html;
  }
  fs.writeFileSync(htmlPath, html, "utf8");
}

function walkHtml(dir) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    if (fs.statSync(p).isDirectory()) walkHtml(p);
    else if (name.endsWith(".html")) injectNativeInit(p);
  }
}

rmDir(wwwDir);
copyRecursive(publicDir, wwwDir);
fs.mkdirSync(nativeInitDir, { recursive: true });
fs.writeFileSync(nativeInitPath, initSource, "utf8");
walkHtml(wwwDir);
console.log("[mobile:prepare] www/ ready from public/; API base:", fromEnv || "(empty — set MOBILE_API_BASE_URL)");
